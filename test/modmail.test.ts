// Runs handleModMail against the fake Devvit runtime (no Reddit calls are made).
// Event and conversation shapes follow what the live platform was seen to send:
// prefixed ids in the trigger, bare ids from the API, `ParticipatingAs_*` roles.
import assert from 'node:assert/strict';
import { beforeEach, test } from 'node:test';
import {
  fake,
  modMailEvent as event,
  modMessage,
  person,
  setMessages,
  userConversation,
  userMessage,
  type Fields,
} from './fake-devvit.ts';

const { handleModMail } = await import('../src/modmail.ts');

const PATTERNS = 'buy followers\n/t\\.me\\/\\w+/i';
/** What a fresh install does on a match: ban, mute, private note, archive. */
const DEFAULT_ACTIONS = ['banUser', 'muteConversation', 'reply', 'archiveConversation'];

const summaryLog = (): Fields[] => (fake.zsets.get('summary:log') ?? []).map((m) => JSON.parse(m.member) as Fields);
/** Forget what was called and which messages were handled, but keep stored lists. */
const nextDelivery = (): void => {
  fake.calls = [];
  for (const key of [...fake.kv.keys()]) if (key.startsWith('handled:')) fake.kv.delete(key);
};

beforeEach(() => {
  fake.reset();
  fake.settings = { patterns: PATTERNS };
  fake.conversation = userConversation(userMessage('m1', 'Buy Followers at t.me/x'));
});

test('default settings: a matching modmail is banned, muted, noted, archived and logged for the summary', async () => {
  await handleModMail(event());
  assert.deepEqual(fake.methods(), DEFAULT_ACTIONS);

  const ban = fake.argsOf('banUser');
  assert.equal(ban.username, 'spammer');
  assert.equal(ban.subredditName, 'testsub');
  assert.equal('duration' in ban, false, 'permanent ban sends no duration');
  assert.equal('message' in ban, false, 'no ban message unless one is set');
  assert.deepEqual(fake.argsOf('muteConversation'), { conversationId: 'c1', numHours: 672 });

  const note = fake.argsOf('reply');
  assert.equal(note.isInternal, true);
  assert.match(note.body as string, /acted on u\/spammer: this message matched the pattern `buy followers`/);
  assert.match(note.body as string, /\* Banned \(permanently\)\n\n\* Muted for 28 days/);
  assert.doesNotMatch(note.body as string, /permanent-mute list/);

  assert.deepEqual(
    summaryLog().map((e) => ({ u: e.u, p: e.p, o: e.o, c: e.c })),
    [{ u: 'spammer', p: 'buy followers', o: ['Banned (permanently)', 'Muted for 28 days'], c: 'c1' }],
  );
  assert.equal(fake.listed('spammer'), undefined, 'a 28-day mute is not a permanent one');
});

test('every modmail API call gets the bare conversation id (mute rejects the prefixed one)', async () => {
  await handleModMail(event());
  assert.deepEqual(fake.argsOf('getConversation'), { conversationId: 'c1' });
  assert.equal(fake.argsOf('muteConversation').conversationId, 'c1');
  assert.equal(fake.argsOf('reply').conversationId, 'c1');
  assert.equal(fake.calls.find((c) => c.method === 'archiveConversation')!.args, 'c1');
});

test('acts whatever label the trigger uses for a regular user', async () => {
  for (const label of ['ParticipatingAs_PARTICIPANT_USER', 'participant_user', 'SOME_FUTURE_LABEL', '']) {
    nextDelivery();
    await handleModMail(event({ messageAuthorType: label }));
    assert.deepEqual(fake.methods(), DEFAULT_ACTIONS, `label "${label}"`);
  }
});

test('non-matching modmail does nothing', async () => {
  setMessages(userMessage('m1', 'why was my post removed?'));
  await handleModMail(event());
  assert.deepEqual(fake.actions(), []);
  assert.deepEqual(summaryLog(), []);
});

test('moderator messages, mod discussions and automated mail never reach Reddit at all', async () => {
  await handleModMail(event({ messageAuthorType: 'ParticipatingAs_MODERATOR' }));
  await handleModMail(event({ messageAuthorType: 'moderator' }));
  await handleModMail(event({ messageAuthorType: 'ParticipatingAs_PARTICIPANT_SR' }));
  await handleModMail(event({ conversationType: 'internal' }));
  await handleModMail(event({ conversationType: 'sr_sr' }));
  await handleModMail(event({ isAutoGenerated: true }));
  assert.deepEqual(fake.calls, []);
});

test('the conversation itself decides who the sender is, even if the trigger label is wrong', async () => {
  const mislabelled = event({ messageAuthorType: 'SOME_FUTURE_LABEL' });

  // A moderator's reply in a user conversation.
  setMessages(modMessage('m1', 'please do not buy followers'));
  await handleModMail(mislabelled);
  assert.deepEqual(fake.actions(), [], 'moderator reply');

  // A mod discussion, exactly as the live API returned one.
  fake.conversation = {
    id: 'c1',
    subject: 'x',
    conversationType: 'internal',
    isInternal: true,
    isAuto: false,
    participant: {},
  };
  setMessages(
    userMessage('m1', 'buy followers', { author: person('modmail-regex-ban', { isMod: true }), isInternal: true }),
  );
  await handleModMail(mislabelled);
  assert.deepEqual(fake.actions(), [], 'mod discussion');
});

test('Reddit admins, moderators and deleted accounts are never banned', async () => {
  for (const flag of ['isAdmin', 'isMod', 'isDeleted']) {
    fake.calls = [];
    setMessages(userMessage('m1', 'buy followers', { author: person('spammer', { [flag]: true }) }));
    await handleModMail(event());
    assert.deepEqual(fake.actions(), [], `author ${flag}`);

    fake.calls = [];
    setMessages(userMessage('m1', 'buy followers'));
    fake.conversation.participant = person('spammer', { [flag]: true });
    await handleModMail(event());
    assert.deepEqual(fake.actions(), [], `participant ${flag}`);
    fake.conversation.participant = person('spammer');
  }
});

test('only the conversation participant can be banned, never a third party', async () => {
  setMessages(userMessage('m1', 'buy followers', { author: person('someone_else') }));
  await handleModMail(event());
  assert.deepEqual(fake.actions(), []);

  fake.calls = [];
  fake.conversation.participant = {};
  setMessages(userMessage('m1', 'buy followers'));
  await handleModMail(event());
  assert.deepEqual(fake.actions(), [], 'no participant');

  fake.calls = [];
  fake.conversation.participant = person('SPAMMER');
  await handleModMail(event());
  assert.equal(fake.argsOf('banUser').username, 'SPAMMER', 'name comparison ignores case');
});

test('automated conversations and private notes are skipped', async () => {
  fake.conversation.isAuto = true;
  await handleModMail(event());
  assert.deepEqual(fake.actions(), []);

  fake.conversation.isAuto = false;
  setMessages(userMessage('m1', 'buy followers', { isInternal: true }));
  await handleModMail(event());
  assert.deepEqual(fake.actions(), []);
});

test("the app never acts on itself: its own summary is a 'user' conversation that quotes the patterns", async () => {
  // The summary exactly as Reddit stored and announced it live: an automated
  // sr_user conversation with no participant, written by the app's moderator
  // account "as a participant user".
  fake.settings = { patterns: 'buy followers\nModmail Regex Ban', muteDuration: ['permanent'] };
  fake.conversation = {
    id: '3vea8i',
    subject: '[notification] Modmail Regex Ban: summary for the past week',
    conversationType: 'sr_user',
    isAuto: true,
    isInternal: false,
    state: 'New',
    participant: {},
    messages: {
      '5k2cik': {
        id: '5k2cik',
        date: '2026-11-16T09:48:53.000000+0000',
        author: person('modmail-regex-ban', { isMod: true, isParticipant: false }),
        participatingAs: 'participant_user',
        isInternal: false,
        bodyMarkdown: 'Modmail Regex Ban acted on **3** modmail messages.\n\n* 1 × matched `buy followers`',
      },
    },
  };
  const ids = { conversationId: 'ModmailConversation_3vea8i', messageId: 'ModmailMessage_5k2cik' };
  await handleModMail(event({ ...ids, isAutoGenerated: true }));
  assert.deepEqual(fake.calls, [], 'the real trigger is flagged as automated and dropped at once');
  await handleModMail(event(ids));
  assert.deepEqual(fake.actions(), [], 'and the conversation itself rules it out as well');

  // Even if Reddit did not flag any of that, and made the app account an
  // ordinary-looking participant, the app must not ban or mute itself.
  fake.calls = [];
  fake.conversation = userConversation(
    userMessage('m1', 'Summary: 3 × matched `buy followers`', { author: person('modmail-regex-ban') }),
  );
  fake.conversation.participant = person('Modmail-Regex-Ban');
  await handleModMail(event());
  assert.deepEqual(fake.actions(), []);
});

test('a redelivered trigger does not act twice, even when both arrive together', async () => {
  await handleModMail(event());
  await handleModMail(event());
  assert.equal(fake.methods().filter((m) => m === 'banUser').length, 1);
  assert.equal(fake.expirations.get('handled:m1'), 24 * 60 * 60, 'the marker expires after a day');

  nextDelivery();
  await Promise.all([handleModMail(event()), handleModMail(event()), handleModMail(event())]);
  assert.equal(fake.methods().filter((m) => m === 'banUser').length, 1);
  assert.equal(fake.methods().filter((m) => m === 'reply').length, 1);
});

test("the sender's text cannot inject Markdown into the moderator note", async () => {
  fake.settings = { patterns: 'crypto.*' };
  setMessages(userMessage('m1', 'crypto [verify your account](http://evil.example) `x` u/mod'));
  await handleModMail(event());
  const note = fake.argsOf('reply').body as string;
  assert.match(note, /matched text: `crypto \[verify your account\]\(http:\/\/evil\.example\) 'x' u\/mod`/);
  assert.equal(note.split('`').length - 1, 4, 'only the two code spans use backticks');
});

test('falls back to the HTML body when the Markdown body is empty', async () => {
  setMessages(userMessage('m1', '', { body: '<p>buy followers</p>' }));
  await handleModMail(event());
  assert.deepEqual(fake.methods(), DEFAULT_ACTIONS);
});

test('a ban message longer than Reddit allows is trimmed, not sent as is', async () => {
  fake.settings = { patterns: PATTERNS, banMessage: 'x'.repeat(1500) };
  await handleModMail(event());
  assert.equal((fake.argsOf('banUser').message as string).length, 1000);
});

test('settings control duration, mute length, and which actions run', async () => {
  // Shapes as the live settings API returned them: select values arrive as arrays.
  fake.settings = {
    patterns: PATTERNS,
    banLength: ['7'],
    banMessage: ' bye ',
    muteDuration: ['72'],
    addModNote: false,
    archive: false,
    summaryFrequency: ['off'],
  };
  await handleModMail(event());
  assert.deepEqual(fake.methods(), ['banUser', 'muteConversation']);
  assert.equal(fake.argsOf('banUser').duration, 7);
  assert.equal(fake.argsOf('banUser').message, 'bye');
  assert.equal(fake.argsOf('muteConversation').numHours, 72);
  assert.deepEqual(summaryLog(), [], 'nothing is stored when summaries are off');

  nextDelivery();
  fake.settings = { ...fake.settings, banEnabled: false };
  await handleModMail(event());
  assert.deepEqual(fake.methods(), ['muteConversation']);

  nextDelivery();
  fake.settings = { ...fake.settings, muteEnabled: false };
  await handleModMail(event());
  assert.deepEqual(fake.calls, [], 'nothing to do, so not even a read');

  nextDelivery();
  fake.settings = { patterns: PATTERNS, muteEnabled: false, muteDuration: ['168'] };
  await handleModMail(event());
  assert.deepEqual(fake.methods(), ['banUser', 'reply', 'archiveConversation'], 'ban only');
});

test('a failed ban is reported in the note and the summary, and does not stop the mute', async () => {
  fake.failures.set('banUser', 'USER_DOESNT_EXIST');
  await handleModMail(event());
  assert.deepEqual(fake.methods(), ['muteConversation', 'reply', 'archiveConversation']);
  assert.match(fake.argsOf('reply').body as string, /\* Ban FAILED: USER_DOESNT_EXIST\n\n\* Muted for 28 days/);
  assert.deepEqual(summaryLog()[0]?.o, ['Ban FAILED: USER_DOESNT_EXIST', 'Muted for 28 days']);
});

test('a conversation exactly as the live API returned it (names changed)', async () => {
  // Captured from a real conversation between a subreddit and a regular user,
  // whose only message was written by the app's own moderator account.
  const liveParticipant = {
    isMod: false,
    isAdmin: false,
    name: 'spammer',
    isOp: false,
    isParticipant: true,
    isApproved: false,
    isHidden: false,
    id: 100000000000001,
    isDeleted: false,
  };
  const liveMessage: Fields = {
    id: '5k29wi',
    date: '2026-11-16T09:12:51.154000+0000',
    author: {
      isMod: true,
      isAdmin: false,
      name: 'the-app-account',
      isOp: true,
      isParticipant: false,
      isApproved: false,
      isHidden: false,
      id: 100000000000002,
      isDeleted: false,
    },
    participatingAs: 'moderator',
    isInternal: false,
    bodyMarkdown: 'Hello. Please do not buy followers.',
  };
  fake.conversation = {
    id: '3ve8t5',
    subject: 'A note from the moderators',
    conversationType: 'sr_user',
    isAuto: false,
    isInternal: false,
    state: 'New',
    participant: liveParticipant,
    messages: { '5k29wi': liveMessage },
  };
  const ids = { conversationId: 'ModmailConversation_3ve8t5', messageId: 'ModmailMessage_5k29wi' };

  // The trigger as it really arrived for that message.
  await handleModMail(event({ ...ids, messageAuthorType: 'ParticipatingAs_MODERATOR', conversationState: 'archived' }));
  assert.deepEqual(fake.calls, [], 'the real trigger is dropped before any API call');

  // Even if the trigger claimed a regular user wrote it, the conversation says otherwise.
  await handleModMail(event(ids));
  assert.deepEqual(fake.actions(), [], 'a moderator-written message is never acted on');

  // The same conversation with that message written by the participant.
  liveMessage.author = { ...liveParticipant };
  liveMessage.participatingAs = 'participant_user';
  fake.calls = [];
  await handleModMail(event(ids));
  assert.deepEqual(fake.methods(), DEFAULT_ACTIONS);
  assert.equal(fake.argsOf('banUser').username, 'spammer');
  assert.deepEqual(fake.argsOf('muteConversation'), { conversationId: '3ve8t5', numHours: 672 });
});

test('subject is matched on the first message only; firstMessageOnly skips replies', async () => {
  fake.settings = { patterns: 'forbidden subject' };
  fake.conversation.subject = 'Forbidden Subject';
  setMessages(userMessage('m1', 'hi'), userMessage('m2', 'still hi'));
  await handleModMail(event({ messageId: 'ModmailMessage_m2' }));
  assert.deepEqual(fake.actions(), [], 'reply is not judged by the subject');
  await handleModMail(event({ messageId: 'm1' }));
  assert.deepEqual(fake.methods(), DEFAULT_ACTIONS);

  fake.calls = [];
  fake.settings = { patterns: 'still', firstMessageOnly: true };
  await handleModMail(event({ messageId: 'ModmailMessage_m2' }));
  assert.deepEqual(fake.actions(), []);
});

test("a user's reply in a conversation a moderator started is checked on its body", async () => {
  fake.conversation.subject = 'Your post was removed: buy followers rule';
  setMessages(modMessage('m1', 'Your post broke the rules.'), userMessage('m2', 'ok, wanna buy followers?'));
  await handleModMail(event({ messageId: 'ModmailMessage_m2' }));
  assert.deepEqual(fake.methods(), DEFAULT_ACTIONS);

  nextDelivery();
  setMessages(modMessage('m1', 'Your post broke the rules.'), userMessage('m2', 'sorry about that'));
  await handleModMail(event({ messageId: 'ModmailMessage_m2' }));
  assert.deepEqual(fake.actions(), [], "the moderator's subject is not held against the user");
});

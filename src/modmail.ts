import { context, reddit, redis, settings } from '@devvit/web/server';
import type { OnModMailRequest } from '@devvit/web/shared';
import { switchedOn } from './builtins.ts';
import { LONGEST_MUTE_HOURS, readConfig, type RawSettings } from './config.ts';
import { recordInLedger, type LedgerKind } from './ledger.ts';
import { findMatch, parsePatterns } from './patterns.ts';
import {
  getKeptMuted,
  listedAction,
  muteEnd,
  removeKeptMuted,
  saveKeptMuted,
  type KeptMuted,
  type ListedAction,
} from './permamute.ts';
import { KEYS } from './storage.ts';
import { isAppAccount } from './self.ts';
import { recordAction } from './summary.ts';
import { asCode, bareId, errorText, isoDate } from './text.ts';

/** Longest text handed to a moderator-written regex, to bound matching time. */
const MAX_TEXT_LENGTH = 20_000;
const DEDUPE_TTL_SECONDS = 24 * 60 * 60;

const EXEMPT = '"Exempt users" in the app settings';

/**
 * The sender's role as a plain word. The trigger sends `ParticipatingAs_MODERATOR`
 * and `ParticipatingAs_PARTICIPANT_USER` (both seen live) although its
 * documentation says `moderator` and `participant_user`; the conversation API
 * sends the lower-case words. Both forms become the lower-case word here.
 */
const role = (value: string | undefined): string =>
  (value ?? '').replace(/^ParticipatingAs_/i, '').toLowerCase();

/** Roles that are never a regular user writing in. */
const NON_USER_ROLES = new Set(['moderator', 'participant_sr']);
/** Mod discussions and subreddit-to-subreddit mail. */
const NON_USER_CONVERSATIONS = new Set(['internal', 'sr_sr']);

/** " (added 2026-11-16 after matching `pattern`)", or as much of that as is known. */
function listedSince(entry: KeptMuted): string {
  const details = [
    entry.since ? `added ${isoDate(entry.since)}` : '',
    entry.pattern ? `after matching ${asCode(entry.pattern)}` : '',
  ].filter(Boolean);
  return details.length ? ` (${details.join(' ')})` : '';
}

export async function handleModMail(event: OnModMailRequest): Promise<void> {
  // Cheap early exits for mail that is clearly not from a regular user: mods,
  // mod discussions, subreddit-to-subreddit mail, automated notices. These only
  // rule mail out; who the sender really is gets decided from the conversation
  // itself further down, so an unexpected label here can never cause a ban.
  if (NON_USER_ROLES.has(role(event.messageAuthorType))) return;
  if (NON_USER_CONVERSATIONS.has(event.conversationType)) return;
  if (event.isAutoGenerated) return;

  const raw = await settings.getAll<RawSettings>();
  const config = readConfig(raw);
  // "Undo everything" is on: the app is reversing what it did, and takes no new action.
  if (config.undoAll) return;
  if (!config.banEnabled && !config.muteEnabled) return;

  // The ready-made patterns that are switched on, then the moderators' own.
  const { patterns: own, errors } = parsePatterns(config.patterns);
  const patterns = [...switchedOn(raw), ...own];
  for (const bad of errors) {
    console.warn(`Skipping invalid pattern on line ${bad.line} (${bad.source}): ${bad.message}`);
  }
  const keepsList = config.permanent !== 'off';
  if (patterns.length === 0 && !keepsList) return;

  const conversationId = bareId(event.conversationId);
  const { conversation, user } = await reddit.modMail.getConversation({ conversationId });
  if (!conversation) return;

  const messages = Object.values(conversation.messages ?? {}).sort(
    (a, b) => Date.parse(a.date ?? '') - Date.parse(b.date ?? ''),
  );
  const messageId = bareId(event.messageId);
  const message = messages.find((m) => bareId(m.id) === messageId);
  if (!message) {
    console.warn(`Message ${event.messageId} not found in conversation ${event.conversationId}`);
    return;
  }

  // Act only when this message was written by the conversation's participant
  // (the non-moderator the conversation is with), and never on moderators,
  // Reddit admins, deleted accounts, private notes or automated conversations.
  const sender = message.author;
  const participant = conversation.participant;
  const username = participant?.name;
  const fromParticipant =
    !!username && !!sender?.name && sender.name.toLowerCase() === username.toLowerCase();
  if (
    !fromParticipant ||
    [sender, participant].some((who) => who?.isMod || who?.isAdmin || who?.isDeleted) ||
    NON_USER_ROLES.has(role(message.participatingAs)) ||
    NON_USER_CONVERSATIONS.has(conversation.conversationType ?? '') ||
    conversation.isInternal ||
    conversation.isAuto ||
    message.isInternal
  ) {
    return;
  }

  // Never the app itself. Its own summary is sent as a "user" conversation
  // written by the app account, and it quotes the patterns.
  const name = username.toLowerCase();
  if (isAppAccount(name)) return;

  if (config.exempt.has(name)) {
    await removeKeptMuted(name);
    return;
  }

  const isFirstMessage = bareId(messages[0]?.id) === messageId;
  let match: ReturnType<typeof findMatch>;
  if (isFirstMessage || !config.firstMessageOnly) {
    const texts: string[] = [];
    // The subject belongs to the opening message; don't re-test it on every reply.
    if (config.matchSubject && isFirstMessage && conversation.subject) {
      texts.push(conversation.subject);
    }
    if (config.matchBody) {
      const body = message.bodyMarkdown || message.body;
      if (body) texts.push(body);
    }
    match = findMatch(
      patterns,
      texts.map((text) => text.slice(0, MAX_TEXT_LENGTH)),
    );
  }

  // No match: the only other reason to act is that this user is on the
  // permanent-mute list and has been able to write in anyway.
  let listed: KeptMuted | undefined;
  let action: ListedAction | undefined;
  if (!match) {
    if (!keepsList) return;
    listed = await getKeptMuted(name);
    if (!listed) return;
    action = listedAction(
      listed,
      Date.parse(message.date ?? '') || Date.now(),
      config.permanent,
      user?.muteStatus?.isMuted === true,
    );
    if (action === 'lifted') {
      console.log(`u/${username} was unmuted by a moderator: removed from the permanent-mute list`);
      await removeKeptMuted(name);
      return;
    }
  }

  // Triggers can be delivered more than once; never act twice for one modmail.
  // The increment is atomic, so only one of two simultaneous deliveries sees 1.
  const dedupeKey = KEYS.handled(messageId);
  if ((await redis.incrBy(dedupeKey, 1)) > 1) return;
  await redis.expire(dedupeKey, DEDUPE_TTL_SECONDS);

  const subredditName = context.subredditName ?? event.conversationSubreddit?.name;
  const outcome: string[] = [];
  /** Keeps a record of each thing the app does, so that it can be undone. */
  const remember = async (kind: LedgerKind): Promise<void> => {
    try {
      await recordInLedger(kind, username, conversationId);
    } catch (err) {
      console.error(`Failed to record the ${kind} of u/${username}: ${errorText(err)}`);
    }
  };

  if (match && config.banEnabled) {
    const days = config.banDays;
    const length = days > 0 ? `${days} day${days === 1 ? '' : 's'}` : 'permanently';
    try {
      if (!subredditName) throw new Error('subreddit name unavailable');
      await reddit.banUser({
        subredditName,
        username,
        reason: config.banReason,
        note: `Modmail regex: ${match.pattern.source}`.slice(0, 300),
        ...(days > 0 ? { duration: days } : {}),
        ...(config.banMessage ? { message: config.banMessage } : {}),
      });
      outcome.push(`Banned (${length})`);
      await remember('ban');
    } catch (err) {
      console.error(`Failed to ban u/${username}: ${errorText(err)}`);
      outcome.push(`Ban FAILED: ${errorText(err)}`);
    }
  }

  if (match ? config.muteEnabled : action === 'remute') {
    const numHours = match ? config.muteHours : LONGEST_MUTE_HOURS;

    // Reddit sends its mute notice on every renewal and apps cannot turn that
    // off. So when a recurring mute starts, tell the user once how to silence
    // those notices. It has to go out before the mute: Reddit will not deliver
    // a moderator's message to someone who is muted (seen live: "Participant
    // has been muted from the subreddit").
    if (match && config.permanent === 'recurring' && config.recurringMessage) {
      try {
        // The counter makes "first time" atomic, so a burst of matching
        // messages arriving together sends the notice once, not once each.
        if (!(await getKeptMuted(name)) && (await redis.incrBy(KEYS.tipSent(name), 1)) === 1) {
          await redis.expire(KEYS.tipSent(name), 60 * 60);
          await reddit.modMail.reply({ conversationId, body: config.recurringMessage, isAuthorHidden: true });
        }
      } catch (err) {
        console.error(`Failed to send u/${username} the renewal-notice message: ${errorText(err)}`);
        outcome.push(`Message to the user FAILED: ${errorText(err)}`);
      }
    }

    const now = Date.now();
    let until = 0;
    try {
      const response = await reddit.modMail.muteConversation({ conversationId, numHours });
      until = muteEnd(response, now);
      outcome.push(`Muted ${action ? 'again ' : ''}for ${numHours / 24} days`);
      await remember('mute');
    } catch (err) {
      console.error(`Failed to mute u/${username}: ${errorText(err)}`);
      outcome.push(`Mute FAILED: ${errorText(err)}`);
    }
    if (keepsList) {
      try {
        await saveKeptMuted(name, {
          since: listed?.since || now,
          pattern: match?.pattern.source ?? listed?.pattern ?? '',
          conversationId,
          at: now,
          until,
        });
      } catch (err) {
        console.error(`Failed to save u/${username} on the permanent-mute list: ${errorText(err)}`);
      }
    }
  }
  if (action === 'archive') outcome.push('Archived automatically');

  console.log(
    `u/${username} ${match ? `matched "${match.pattern.source}"` : 'is on the permanent-mute list'}: ${outcome.join('; ')}`,
  );

  if (config.addModNote) {
    const paragraphs: string[] = [];
    if (match) {
      const matchedText = asCode(match.matched.slice(0, 200));
      paragraphs.push(
        `Modmail Regex Ban acted on u/${username}: this message matched the pattern ${asCode(match.pattern.source)}` +
          (matchedText ? ` (matched text: ${matchedText}).` : '.'),
        ...outcome.map((line) => `* ${line}`),
      );
      if (config.permanent === 'recurring') {
        paragraphs.push(
          'Permanent mute (recurring): the app will renew this 28-day mute shortly before it ends, for as long as ' +
            `they stay on its permanent-mute list. To lift it, unmute them in Reddit or add them to ${EXEMPT}.`,
        );
      } else if (config.permanent === 'archive') {
        paragraphs.push(
          'Permanent mute (auto-archive): once this 28-day mute has ended, the app will archive anything they ' +
            `send. To lift it, unmute them in Reddit before then, or add them to ${EXEMPT}.`,
        );
      }
    } else if (listed) {
      const who = `Modmail Regex Ban: u/${username} is on this subreddit's permanent-mute list${listedSince(listed)}`;
      paragraphs.push(
        action === 'remute'
          ? `${who} and wrote in after their mute had lapsed. This message was archived automatically.`
          : `${who}, so this message was archived automatically.`,
        ...outcome.filter((line) => line !== 'Archived automatically').map((line) => `* ${line}`),
        // With recurring mutes a moderator's unmute lifts it; with auto-archive
        // there is no mute to undo, so only the exempt list does.
        config.permanent === 'recurring'
          ? `To stop this, unmute them in Reddit or add them to ${EXEMPT}.`
          : `To stop this, add them to ${EXEMPT}.`,
      );
    }
    try {
      await reddit.modMail.reply({ conversationId, isInternal: true, body: paragraphs.join('\n\n') });
    } catch (err) {
      console.error(`Failed to add mod note: ${errorText(err)}`);
    }
  }

  // Mail from someone on the permanent-mute list is always archived; for a
  // pattern match it is the moderators' choice.
  if (action || config.archive) {
    try {
      await reddit.modMail.archiveConversation(conversationId);
      await remember('archive');
    } catch (err) {
      console.error(`Failed to archive conversation: ${errorText(err)}`);
    }
  }

  if (config.summary !== 'off') {
    try {
      await recordAction({
        t: Date.now(),
        u: username,
        p: match?.pattern.source ?? '',
        o: outcome,
        c: conversationId,
      });
    } catch (err) {
      console.error(`Failed to record the action for the summary: ${errorText(err)}`);
    }
  }
}
